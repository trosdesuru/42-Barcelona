void	ft_ultimate_div_mod(int *a, int *b)
{
	int	ptr_a;
	int	ptr_b;

	if (*b != 0)
	{
		ptr_a = *a;
		ptr_b = *b;
		*a = ptr_a / ptr_b;
		*b = ptr_a % ptr_b;
	}
}
